/**
 * Kanıt dosyasına göre doğrulanmış Kolay (A1-A2) kelimeleri döner.
 * @returns {Set<string>}
 */
export function getVerifiedKolayWords() {
  const evidencePath = path.join(DATA_SRC, 'level-evidence.jsonl')
  if (!fs.existsSync(evidencePath)) {
    throw new Error(`Kanıt dosyası bulunamadı: ${evidencePath}`)
  }

  const lines = fs
    .readFileSync(evidencePath, 'utf-8')
    .split('\n')
    .filter(Boolean)
    .map(l => JSON.parse(l))
  const evMap = new Map(lines.map(e => [e.w, e]))

  const result = new Set()

  // 1. Çekirdek çapaları sözlükte doğrula
  for (const w of CORE_KOLAY_ANCHORS) {
    if (evMap.has(w) && !BLOCKLIST.has(w)) {
      const e = evMap.get(w)
      if (!e.flags.is_archaic && !e.flags.is_dialect) {
        result.add(w)
      }
    }
  }

  // 2. Çok yüksek frekanslı günlük kelimeleri dahil et (OpenSub <= 3500 veya Azer 1k veya Zemberek <= 1500)
  for (const e of lines) {
    if (BLOCKLIST.has(e.w)) continue
    if (e.flags.is_archaic || e.flags.is_dialect || e.flags.is_technical) continue

    const isHighFreq =
      (e.freq.opensub_rank !== null && e.freq.opensub_rank <= 3500) ||
      e.freq.in_azer_1k ||
      (e.freq.zemberek_rank !== null && e.freq.zemberek_rank <= 1500)

    if (isHighFreq) {
      result.add(e.w)
    }
  }

  return result
}
